
"""Integration tests for the real assignment engine and comparison page."""

import pathlib

from app import create_app
from app.contract import mocks
from app.persistence import repositories
from app.visualization.routes import _build_overview


def test_real_engine_comparison(tmp_path: pathlib.Path, monkeypatch) -> None:
    """Check that real solver results reach the comparison page."""
    db_file = tmp_path / "test_maja_comparison.db"

    app = create_app({"TESTING": True, "DATABASE_PATH": db_file})
    client = app.test_client()

    # Do not allow the application to use the mock engine.
    def mock_not_allowed(*args, **kwargs):
        raise AssertionError("The mock engine was used!")

    monkeypatch.setattr(
        mocks.MockAssignmentEngine, "execute_run", mock_not_allowed
    )
    monkeypatch.setattr(
        mocks.MockAssignmentEngine, "compare_solutions", mock_not_allowed
    )

    # Load a cohort and run the real solver.
    seed_response = client.post("/load-scenario/standard")
    assert seed_response.status_code == 302

    run_response = client.post(
        "/runs/trigger",
        data={"primary_strategy": "PREFERENCE", "max_alternatives": 3},
    )
    assert run_response.status_code == 302

    # Retrieve the actual solutions and their metrics.
    with app.app_context():
        runs = repositories.RunRepository().list_runs(limit=1)
        assert len(runs) == 1

        run = runs[0]
        assert run.status == "COMPLETED"
        assert len(run.solutions) >= 2

        overview = _build_overview(run.solutions)

        # Check that the comparison uses the real metric values.
        for row in overview:
            for solution, value in zip(run.solutions, row["values"]):
                group = (
                    "efficiency"
                    if row["key"] in (
                        "mean_skill_fit",
                        "unmet_soft_requirements_count",
                    )
                    else "fairness"
                )
                assert value == solution.indicators[group][row["key"]]

        first_id = run.solutions[0].id
        second_id = run.solutions[1].id
        run_id = run.id

    # Verify that the comparison page displays the results.
    response = client.get(
        f"/compare?run={run_id}&sol1={first_id}&sol2={second_id}"
    )

    assert response.status_code == 200
    assert b"Average skill fit" in response.data
    assert b"Average preference rank" in response.data



def test_real_engine_recommendations(tmp_path: pathlib.Path, monkeypatch) -> None:
    """Check that recommendations use real solver results and metrics."""
    db_file = tmp_path / "test_maja_recommendations.db"

    app = create_app({"TESTING": True, "DATABASE_PATH": db_file})
    client = app.test_client()

    # Make sure the mock engine cannot be used.
    def mock_not_allowed(*args, **kwargs):
        raise AssertionError("The mock engine was used!")

    monkeypatch.setattr(
        mocks.MockAssignmentEngine, "execute_run", mock_not_allowed
    )

    # Generate real solutions.
    client.post("/load-scenario/standard")

    response = client.post(
        "/runs/trigger",
        data={"primary_strategy": "PREFERENCE", "max_alternatives": 3},
    )
    assert response.status_code == 302

    # Get the solutions generated by Team B.
    with app.app_context():
        runs = repositories.RunRepository().list_runs(limit=1)
        assert len(runs) == 1

        run = runs[0]
        assert run.status == "COMPLETED"
        assert run.solutions

        solutions = run.solutions

        # Determine which solution should win each criterion.
        best_preference = min(
            solutions,
            key=lambda s: (
                s.indicators["fairness"]["unranked_count"],
                s.indicators["fairness"]["mean_rank"],
                s.indicators["fairness"]["worst_rank"],
            ),
        )

        best_skill = max(
            solutions,
            key=lambda s: (
                s.indicators["efficiency"]["mean_skill_fit"],
                -s.indicators["efficiency"]["unmet_soft_requirements_count"],
            ),
        )

        best_fairness = min(
            solutions,
            key=lambda s: (
                s.indicators["fairness"]["rank_gini"],
                s.indicators["fairness"]["rank_variance"],
                s.indicators["fairness"]["mean_rank"],
            ),
        )

        # Check the actual recommendation generator.
        from app.engine import recommendations

        recs = recommendations.generate_recommendations(solutions)

        assert len(recs) == 3
        assert recs[0].recommended_solution_id == best_preference.id
        assert recs[1].recommended_solution_id == best_skill.id
        assert recs[2].recommended_solution_id == best_fairness.id

        run_id = run.id

    # Verify the recommendation page displays the results.
    page = client.get(f"/recommendations/{run_id}")

    assert page.status_code == 200
    assert b"Calculated Evidence" in page.data
    assert b"Policy Advice" in page.data
